#!/usr/bin/env python3
"""Regenerate the direct ANGLE GLES2Interface forwarding implementation.

Run from any directory after fetching the pinned ANGLE sources. Extension
entrypoints are resolved once, without a command buffer or per-call allocation.
Methods without native equivalents deliberately fail the unsupported contract;
WebGL's reachable adapter-specific operations are implemented in the provider.
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[4]
HERE = pathlib.Path(__file__).resolve().parent
CUSTOM = set('''GetError GetString GetStringi GetIntegerv GetGraphicsResetStatusKHR
GetRequestableExtensionsCHROMIUM RequestExtensionCHROMIUM Flush Finish
ShallowFinishCHROMIUM OrderingBarrierCHROMIUM DescheduleUntilFinishedCHROMIUM
GetLastFlushIdCHROMIUM ContextVisibilityHintCHROMIUM
InvalidateReadbackBufferShadowDataCHROMIUM LoseContextCHROMIUM
BlitFramebufferCHROMIUM RenderbufferStorageMultisampleCHROMIUM
BindBuffer BufferData BufferSubData MapBufferCHROMIUM UnmapBufferCHROMIUM
BeginQueryEXT EndQueryEXT DeleteQueriesEXT
MultiDrawElementsWEBGL MultiDrawElementsInstancedWEBGL
MultiDrawElementsInstancedBaseVertexBaseInstanceWEBGL'''.split())
ALIASES = {
    'TexStorage2DEXT': 'TexStorage2DEXT',
    'MemoryBarrierEXT': 'MemoryBarrier',
    'MultiDrawArraysWEBGL': 'MultiDrawArraysANGLE',
    'MultiDrawArraysInstancedWEBGL': 'MultiDrawArraysInstancedANGLE',
    'MultiDrawArraysInstancedBaseInstanceWEBGL': 'MultiDrawArraysInstancedBaseInstanceANGLE',
}
CORE_ALIASES = {
    'TexStorage2DEXT': 'TexStorage2D',
    'GenQueriesEXT': 'GenQueries',
    'IsQueryEXT': 'IsQuery',
    'GetQueryivEXT': 'GetQueryiv',
    'GetQueryObjectuivEXT': 'GetQueryObjectuiv',
    'GenVertexArraysOES': 'GenVertexArrays',
    'DeleteVertexArraysOES': 'DeleteVertexArrays',
    'IsVertexArrayOES': 'IsVertexArray',
    'BindVertexArrayOES': 'BindVertexArray',
    'DrawArraysInstancedANGLE': 'DrawArraysInstanced',
    'DrawElementsInstancedANGLE': 'DrawElementsInstanced',
    'VertexAttribDivisorANGLE': 'VertexAttribDivisor',
    'DrawBuffersEXT': 'DrawBuffers',
}


def generate():
    interface = (ROOT / 'gpu/command_buffer/client/gles2_interface_autogen.h').read_text()
    headers = '\n'.join(p.read_text() for folder in ('GLES2', 'GLES3')
                        for p in (ROOT / 'third_party/angle/include' / folder).glob('*.h'))
    native = set(re.findall(r'\bgl(\w+)\s*\(', headers))
    out = ['// Generated by generate_webgl_forwarding.py; do not edit.',
           '// Included inside DirectGLES2. Every native call binds its owner.']
    for result, name, params in re.findall(
            r'virtual\s+(.+?)\s+(\w+)\s*\((.*?)\)\s*=\s*0;', interface, re.S):
        result = ' '.join(result.split())
        params = ' '.join(params.split())
        if name in CUSTOM:
            continue
        params = re.sub(r'\s*=\s*0(?=,|$)', '', params)
        arguments = [] if not params else [re.search(r'(\w+)\s*$', p).group(1)
                                           for p in params.split(',')]
        native_name = ALIASES.get(name, name)
        out.append(f'{result} {name}({params}) override {{')
        if native_name not in native:
            out.append(f'    Unsupported("{name}");')
        else:
            failed = 'return;' if result == 'void' else 'return {};'
            out.append(f'    if (!MakeCurrent()) {{ {failed} }}')
            types = [re.sub(r'\b' + arg + r'\s*$', '', p).strip()
                     for p, arg in zip(params.split(','), arguments)] if params else []
            out.append(f'    using Proc = {result} (GL_APIENTRY*)({", ".join(types)});')
            out.append(f'    static const auto proc = Resolve<Proc>("gl{native_name}");')
            if name in CORE_ALIASES:
                out.append(f'    static const auto core = Resolve<Proc>("gl{CORE_ALIASES[name]}");')
                out.append(f'    if (version_ == 3) return core({", ".join(arguments)});')
            out.append(f'    return proc({", ".join(arguments)});')
        out.append('}')
    (HERE / 'webgl_gles2_forwarding_autogen.inc').write_text('\n'.join(out) + '\n')


if __name__ == '__main__':
    generate()
